def _load_points() -> list[tuple[float, float]]:
    return [
        (
            float(x) * path_scale_x + path_offset_x_um,
            float(y) * path_scale_y + path_offset_y_um,
        )
        for x, y in CENTERLINE_POINTS
    ]


def _polyline_length(points: list[tuple[float, float]]) -> float:
    return sum(
        math.hypot(x1 - x0, y1 - y0)
        for (x0, y0), (x1, y1) in zip(points, points[1:])
    )


@gf.cell
def recreate_spiral_delay() -> gf.Component:
    points = _load_points()
    path = gf.Path(points)
    if delta_length:
        path.append(gf.path.straight(length=delta_length))

    xs = gf.CrossSection(
        sections=[
            gf.Section(
                width=wg_width_um,
                layer=layer,
                port_names=("o1", "o2"),
                port_types=("optical", "optical"),
            )
        ]
    )
    return path.extrude(xs)


def main() -> None:
    here = Path(__file__).resolve().parent
    points = _load_points()
    base_length = _polyline_length(points)
    total_length = base_length + delta_length

    c = recreate_spiral_delay()
    c.write_gds(here / gds_file, with_metadata=False)

    (here / "lengths.json").write_text(
        json.dumps(
            {
                "arms": {
                    "untrimmed_spiral": base_length,
                    "trimmed_spiral": total_length,
                },
                "delta_length_um": abs(total_length - base_length),
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
