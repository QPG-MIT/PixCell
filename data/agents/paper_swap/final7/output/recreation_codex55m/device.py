def add_rect(component: gf.Component, x0: float, y0: float, width: float, height: float) -> None:
    ref = component << gf.components.rectangle(size=(width, height), layer=LAYER)
    ref.move((x0, y0))


def add_delta_knob(component: gf.Component) -> float:
    if delta_length <= 0:
        return 0.0
    path = gf.Path([(footprint_length_um + 0.2, 2.75), (footprint_length_um + 0.2 + delta_length, 2.75)])
    component << path.extrude(width=bus_width_um, layer=LAYER)
    return delta_length


@gf.cell
def recreated_device() -> gf.Component:
    c = gf.Component()
    for x0, y0, width, height in SLICE_RUNS:
        add_rect(c, x0, y0, width, height)

    delta_path = add_delta_knob(c)
    base_arm_length_um = 2 * 3.14159 * ((ring_rx_um + ring_ry_um) / 2)
    c.info["lengths"] = {
        "arms": {
            "reference": base_arm_length_um,
            "tuned": base_arm_length_um + delta_length,
        },
        "outer_ring_centerline_um": 2 * 3.14159 * ((ring_rx_um + ring_ry_um) / 2),
        "transfer_length_um": transfer_length,
        "delta_knob_path_um": delta_path,
        "delta_length_um": delta_length,
    }
    return c


