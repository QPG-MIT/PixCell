"""Four-port waveguide crossing with circular-arc lens tapers.

Two single-mode strip waveguides cross at 90 deg.  Each of the four arms
carries one biconvex, lens-shaped flare centred a short distance out from the
intersection.  The flare expands the mode laterally, which narrows its angular
spectrum, so the beam stays collimated while it traverses the unguided gap left
by the orthogonal arm; the opposing lens re-collects and refocuses it.  That is
what buys low insertion loss and low crosstalk in a crossing this compact.

The lobe sidewalls in the source figure are two circular arcs (fitted to 0.68 nm
RMS over 151 sample columns; an ellipse fits 12x worse, a parabola 4x worse), so
the lens is generated by extruding a straight path through a cross-section whose
width follows the exact circular-segment profile.

Primitives only: gf.Path + extrude, boolean, @gf.cell.  No gf.components device
stencils, no raw polygons.
"""

from __future__ import annotations

import json
from pathlib import Path

import gdsfactory as gf
import numpy as np
from gdsfactory.cross_section import CrossSection, Section

# --------------------------------------------------------------------------
# Tunables (top-level `name = value`, JEE-substitutable)
# --------------------------------------------------------------------------

# --- function knobs -------------------------------------------------------
wg_width = 0.232         # single-mode access waveguide / lens tip width (um)
lens_width = 0.9142      # max width of the lens flare (um)  -- mode expansion
lens_length = 2.0913     # axial length of the lens (um)     -- self-imaging length
lens_offset = 0.8713     # crossing centre -> lens centre (um) -- core overlap / crosstalk
delta_length = 0.0       # horizontal-vs-vertical channel path-length imbalance (um)

# --- layout / routing knobs ----------------------------------------------
arm_length = 2.35        # crossing centre -> port face (um)
n_arms = 4               # ports (4 = crossing)

# --- discretisation / process --------------------------------------------
n_points = 601           # sidewall sampling points per lens
layer = (1, 0)
gds_filename = "device.gds"
lengths_filename = "lengths.json"


# --------------------------------------------------------------------------
# Lens geometry: the circular-segment width profile
# --------------------------------------------------------------------------

def snap_width(w: float) -> float:
    """Snap a width to an even number of dbu.

    kfactory requires port / cross-section widths to be a multiple of 0.002 um
    so that extrusions stay symmetric about the centreline.  The tunables stay
    free-form; only the value handed to kfactory is snapped (sub-nm effect).
    """
    return round(w * 500.0) / 500.0


def lens_arc_radius(length: float, width: float) -> float:
    """Radius of the two circular arcs bounding a lens of `length` x `width`.

    A circular segment of half-chord L = length/2 and sagitta b = width/2 sits
    on a circle of radius R = (L**2 + b**2) / (2 b).  The lens is the
    intersection of two such circles, offset by +/- (R - b) from the axis.
    """
    half_length = 0.5 * length
    half_width = 0.5 * width
    return (half_length**2 + half_width**2) / (2.0 * half_width)


def lens_width_profile(t, *, length: float, width: float, tip_width: float):
    """Width of the lens at normalised arclength `t` in [0, 1].

    Clipped from below at `tip_width` so the lens merges into the access
    waveguide rather than pinching to a degenerate zero-width polygon.
    """
    radius = lens_arc_radius(length, width)
    offset = radius - 0.5 * width
    s = (np.asarray(t) - 0.5) * length                      # axial coord, lens-centred
    half = np.sqrt(np.clip(radius**2 - s**2, 0.0, None)) - offset
    return np.maximum(2.0 * half, tip_width)


def lens_cross_section(*, length: float, width: float, tip_width: float) -> CrossSection:
    section = Section(
        width=snap_width(tip_width),
        layer=layer,
        width_function=lambda t: lens_width_profile(
            t, length=length, width=width, tip_width=tip_width
        ),
    )
    return CrossSection(sections=(section,))


# --------------------------------------------------------------------------
# Assembly
# --------------------------------------------------------------------------

@gf.cell
def crossing_lens(
    wg_width: float = wg_width,
    lens_width: float = lens_width,
    lens_length: float = lens_length,
    lens_offset: float = lens_offset,
    delta_length: float = delta_length,
    arm_length: float = arm_length,
    n_arms: int = n_arms,
    n_points: int = n_points,
) -> gf.Component:
    """Four-port lens-taper waveguide crossing."""
    c = gf.Component()

    # Channel path lengths: delta_length lengthens the horizontal channel's
    # access guides relative to the vertical channel's (split over its two arms).
    arm_h = arm_length + 0.5 * delta_length
    arm_v = arm_length

    paths: dict[str, gf.Path] = {}
    pieces: list[gf.Component] = []

    # --- the two crossing access waveguides (straight, full length) --------
    bus_h = gf.path.straight(length=2.0 * arm_h, npoints=2)
    bus_h.move((-arm_h, 0.0))
    paths["bus_horizontal"] = bus_h
    pieces.append(gf.path.extrude(bus_h, layer=layer, width=snap_width(wg_width)))

    bus_v = gf.path.straight(length=2.0 * arm_v, npoints=2)
    bus_v.rotate(90.0)
    bus_v.move((0.0, -arm_v))
    paths["bus_vertical"] = bus_v
    pieces.append(gf.path.extrude(bus_v, layer=layer, width=snap_width(wg_width)))

    # --- the lens flares, one per arm -------------------------------------
    xs = lens_cross_section(length=lens_length, width=lens_width, tip_width=wg_width)
    inner = lens_offset - 0.5 * lens_length          # lens tip nearest the core

    for i in range(n_arms):
        angle = i * 360.0 / n_arms
        p = gf.path.straight(length=lens_length, npoints=n_points)
        p.rotate(angle)
        p.move((inner * np.cos(np.radians(angle)), inner * np.sin(np.radians(angle))))
        paths[f"lens_{int(round(angle))}deg"] = p
        pieces.append(gf.path.extrude(p, cross_section=xs))

    # --- merge into a single polygon --------------------------------------
    merged = pieces[0]
    for piece in pieces[1:]:
        merged = gf.boolean(merged, piece, operation="or", layer=layer)
    c.add_ref(merged)
    c.flatten()

    # --- optical ports ----------------------------------------------------
    for name, (x, y), orient in (
        ("o1", (-arm_h, 0.0), 180.0),
        ("o2", (0.0, arm_v), 90.0),
        ("o3", (arm_h, 0.0), 0.0),
        ("o4", (0.0, -arm_v), 270.0),
    ):
        c.add_port(name=name, center=(x, y), width=snap_width(wg_width), orientation=orient, layer=layer)

    c.info["paths"] = {k: float(v.length()) for k, v in paths.items()}
    return c


def write_lengths(component: gf.Component, out: Path) -> dict:
    """Channel lengths, computed from the gf.Path centrelines (never hand-entered)."""
    lengths = component.info["paths"]
    horizontal = float(lengths["bus_horizontal"])
    vertical = float(lengths["bus_vertical"])
    data = {
        # exactly the two optical channels of the crossing
        "arms": {"horizontal_um": horizontal, "vertical_um": vertical},
        "delta_length_um": horizontal - vertical,
        "lenses_um": {k: float(v) for k, v in lengths.items() if k.startswith("lens_")},
    }
    out.write_text(json.dumps(data, indent=2))
    return data


if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    component = crossing_lens()
    # with_metadata=False: kfactory's $$$CONTEXT_INFO$$$ cell *references* the
    # device cell, which makes the device cell non-top-level for gdstk readers
    # (they then see an empty layout).  Write a clean single-top-cell GDS.
    component.write_gds(here / gds_filename, with_metadata=False)
    info = write_lengths(component, here / lengths_filename)

    bbox = component.bbox()
    print(f"bbox um : {bbox.width():.4f} x {bbox.height():.4f}")
    print(f"area um2: {component.area(layer):.4f}")
    print(f"polygons: {sum(len(v) for v in component.get_polygons().values())}")
    print(f"lengths : {info['arms']['horizontal_um']:.4f} / "
          f"{info['arms']['vertical_um']:.4f}  delta={info['delta_length_um']:.4f}")
