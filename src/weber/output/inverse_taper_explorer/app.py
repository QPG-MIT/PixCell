    component = create_device_with_sliders(slider_values)

    # Add custom primitives to the component
    for prim in st.session_state.get("custom_primitives", []):
        prim_type = prim["type"]
        layer = prim["layer"]
        params = prim["params"]
        x, y = prim["x"], prim["y"]

        # Create the primitive component
        if prim_type == "rectangle":
            prim_comp = gf.components.rectangle(
                size=(params.get("width", 0.5), params.get("height", 0.3)),
                layer=layer,
                centered=True
            )
        elif prim_type == "circle":
            prim_comp = gf.components.circle(
                radius=params.get("radius", 0.2),
                layer=layer
            )
        elif prim_type == "ellipse":
            prim_comp = gf.components.ellipse(
                radii=(params.get("rx", 0.3), params.get("ry", 0.2)),
                layer=layer
            )
        elif prim_type == "triangle":
            prim_comp = gf.components.triangle(
                x=params.get("x", 0.3),
                y=params.get("y", 0.3),
                layer=layer
            )
        elif prim_type == "straight":
            xs = gf.cross_section.cross_section(
                width=params.get("width", 0.3),
                layer=layer,
                radius=0.1
            )
            prim_comp = gf.components.straight(
                length=params.get("length", 1.0),
                cross_section=xs
            )
        else:
            continue

        # Add to component at specified position
        ref = component.add_ref(prim_comp)
        ref.move((x, y))

