                new_x = st.number_input("New X", -10.0, 10.0, prim['x'], 0.05, key="int_move_x")
                new_y = st.number_input("New Y", -10.0, 10.0, prim['y'], 0.05, key="int_move_y")

                col_a, col_b = st.columns(2)
                with col_a:
                    if st.button("Update", use_container_width=True):
                        st.session_state.custom_primitives[selected_idx]['x'] = new_x
                        st.session_state.custom_primitives[selected_idx]['y'] = new_y
