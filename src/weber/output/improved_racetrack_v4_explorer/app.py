def create_device(config, global_params):
    """Build the device with current configuration."""
    import uuid
    uid = str(uuid.uuid4())[:8]
    c = gf.Component(f"Device_{uid}")

    # Get layer assignments
    layer_assignments = {}
    for slot_id in DEVICE_SLOTS.keys():
        layer_name = st.session_state.weber_layer_assignments.get(slot_id, "Layer 1")
        layer_assignments[slot_id] = get_layer_tuple(layer_name)

    # Build each slot
    for slot_id, slot_config in config.items():
        comp_type = slot_config.get("type", "unknown")
        params = slot_config.get("params", {})
        layer = layer_assignments.get(slot_id, (1, 0))

        try:
            comp = create_component(comp_type, params, layer)
            ref = c.add_ref(comp)
            # Simple grid layout for now
            # Real positioning would use the device topology
        except Exception as e:
            pass

    return c


