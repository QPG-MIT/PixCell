def build_device(
    slider_values: Dict[str, float],
    layer_assignments: Dict[str, Tuple[int, int]] = None
) -> gf.Component:
    """
    Build the device by executing the original script with slider values injected.

    Args:
        slider_values: Dict mapping parameter name to slider value
        layer_assignments: Optional {slot_id: (layer, datatype)}. Applied by
            overriding the script's top-level layer-tuple variables. When the
            script routes everything through ONE shared layer variable (the
            common contract shape), a uniform assignment retargets the whole
            device; non-uniform assignments fall back to the first value.

    Returns:
        GDSFactory Component
    """
    # @gf.cell caches by cell name in a GLOBAL registry — without clearing it,
    # every rebuild returns the first-built geometry no matter what the
    # sliders say (a deceptive explorer). Clear before each build.
    try:
        gf.clear_cache()
    except Exception:
        pass

    # Create a fresh namespace with gdsfactory available
    namespace = {
        'gf': gf,
        'gdsfactory': gf,
        '__name__': '__weber_execution__',
    }

    # Execute the original script FIRST, then override its top-level tunables
    # with the slider values. (Injecting before exec is a no-op for scripts
    # that declare knobs as top-level `name = value` assignments — the
    # parametric contract — because the script's own assignments would
    # clobber the injected values.)
    exec(ORIGINAL_SOURCE, namespace)
    for name, value in slider_values.items():
        namespace[name] = value

    # Apply layer assignments by overriding top-level layer-tuple variables
    # (the main function reads them as globals, same as the sliders).
    if layer_assignments:
        assigned = list(dict.fromkeys(layer_assignments.values()))
        target_layer = tuple(assigned[0])
        for name, value in list(namespace.items()):
            if (
                isinstance(value, tuple) and len(value) == 2
                and all(isinstance(v, int) for v in value)
                and "layer" in name.lower()
            ):
                namespace[name] = target_layer

    # Call the main function to get the component
    main_func_name = MAIN_FUNCTION
    if main_func_name and main_func_name in namespace:
        component = namespace[main_func_name]()
    else:
        # Fallback: look for any @gf.cell function result
        component = None
        for key, val in namespace.items():
            if isinstance(val, gf.Component):
                component = val
                break

    if component is None:
        raise RuntimeError("Could not build component from original script")

    return component


def build_device_from_config(
    config: Dict[str, Dict[str, Any]],
    global_params: Dict[str, float],
    layer_assignments: Dict[str, Tuple[int, int]] = None
) -> gf.Component:
    """
    Build device from slot configuration.

    This converts the slot config format to slider values and calls build_device.

    Args:
        config: Dict mapping slot_id to {type, params}
        global_params: Global parameter values
        layer_assignments: Optional layer assignments

    Returns:
        GDSFactory Component
    """
    # Convert config to flat slider values
    slider_values = {}

    # Add global params
    slider_values.update(global_params)

    # Extract params from slot configs
    for slot_id, slot_config in config.items():
        params = slot_config.get("params", {})
        for param_name, param_value in params.items():
            # Use slot_param naming or direct param name
            slider_values[param_name] = param_value

    return build_device(slider_values, layer_assignments)


