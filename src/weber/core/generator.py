def generate_explorer(
    script_path: str,
    slots: SlotConfig,
    output_dir: Optional[str] = None,
    include_tidy3d: bool = False,
    device_name: Optional[str] = None,
    provenance: Optional[dict] = None,
) -> Path:
    """
    Generate a complete explorer application from slot configuration.

    Args:
        script_path: Path to the original GDSFactory script
        slots: SlotConfig with slot definitions
        output_dir: Output directory (default: output/{script_name}_explorer)
        include_tidy3d: Whether to include Tidy3D simulation panel
        device_name: Optional device name (default: derived from script name)
        provenance: Optional gate/recreation metadata to surface in the app
            (keys used: device_identification, iou, dice, footprint_um,
            function_defining_knobs — all optional)

    Returns:
        Path to the generated explorer directory
    """
    script_path = Path(script_path)

    # Determine output directory
    if output_dir is None:
        name = script_path.stem
        output_dir = OUTPUT_DIR / f"{name}_explorer"
    else:
        output_dir = Path(output_dir)

    output_dir.mkdir(parents=True, exist_ok=True)

    # Determine device name
    if device_name is None:
        device_name = script_path.stem.replace("_", " ").title()

    # Drop knobs the script never actually consumes (assigned but never read):
    # a slider that moves nothing is a deceptive control. Usage = the name
    # appears beyond its own assignment.
    source = script_path.read_text()

    def _is_used(name: str) -> bool:
        return len(re.findall(rf"\b{re.escape(name)}\b", source)) > 1

    slots.global_params = [gp for gp in slots.global_params if _is_used(gp.name)]

    # Copy template files
    _copy_templates(output_dir, include_tidy3d)

    # Generate slot_definitions.py
    _generate_slot_definitions(slots, output_dir / "slot_definitions.py")

    # Generate device_builder.py (parameterized version of original script)
    _generate_device_builder(script_path, slots, output_dir / "device_builder.py")

    # Generate app.py
    _generate_app(slots, output_dir / "app.py", device_name, include_tidy3d,
                  provenance=provenance)

    return output_dir


def _copy_templates(output_dir: Path, include_tidy3d: bool) -> None:
    """Copy template files to output directory."""
    templates_to_copy = [
        "ui_generators.py",
        "visualization.py",
        "layer_manager.py",
        "webgl_viewer.py",
        "viewer_3d.py",
    ]

    if include_tidy3d:
        templates_to_copy.append("tidy3d_integration.py")

    for template_name in templates_to_copy:
        src = TEMPLATES_DIR / template_name
        dst = output_dir / template_name
        if src.exists():
            shutil.copy2(src, dst)

    # Also copy the logo for branding (assets/ lives at the checkout root;
    # installed runs simply skip the branding copy)
    from homi.paths import repo_root

    _root = repo_root()
    if _root is not None:
        logo_src = _root / "assets" / "logo.jpeg"
        if logo_src.exists():
            shutil.copy2(logo_src, output_dir / "logo.jpeg")


